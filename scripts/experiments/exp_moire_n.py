"""Is the interference texture (moire/weave) sensitive to n at the +-1 level?

A pitch component with period p samples starts window k at phase
2*pi*(k*n mod p)/p: the whole across-column interference pattern is
generated by n mod p. Bumping n by 1 changes n mod p for every p at
once, so the moire geometry should reshuffle completely within one
pitch period (~30 samples at 10 kHz) while aggregate statistics barely
move. If true, n is a free texture knob at essentially fixed print size
and fidelity - the premise of the paper-first workflow.

The probe: one song, one rate, n in {n0, n0+1, n0+3, n0+10, n0+30}.
Reported per variant: rho, loop drift, the 12 phi metrics (including
moire_salience), and the correlation of the overlapping n0 x n0 region
of the signed render against the n0 baseline (reshuffling -> ~0).

Run: .venv/bin/python scripts/exp_moire_n.py
       [--track 029 --f 10002 --n0 1728 --deltas 0,1,3,10,30 --clip 99.5]
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from loopviz.paper.matviz import gray, save_rgb
from loopviz.paper.metrics import METRIC_NAMES, features
from loopviz.paper.sheet import make_sheet
from loopviz.songmatrix import Plan, build, load_audio, loop_degradation, materialize

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "runs" / "exp_moire_n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--track", default="029")
    ap.add_argument("--f", type=float, default=10002.0)
    ap.add_argument("--n0", type=int, default=1728)
    ap.add_argument("--deltas", default="0,1,3,10,30")
    ap.add_argument("--clip", type=float, default=99.5)
    args = ap.parse_args()
    deltas = [int(d) for d in args.deltas.split(",")]
    OUT.mkdir(parents=True, exist_ok=True)

    signal, T = load_audio([ROOT / "data" / "audio" / f"{args.track}.wav"])
    print(f"track {args.track}: T={T:.1f}s, f={args.f:.0f} Hz, "
          f"n0={args.n0}, deltas={deltas}")

    rows, tiles, base = [], [], None
    for d in deltas:
        n = args.n0 + d
        N = max(2, round(args.f * T / n))
        pl = Plan(n=n, N=N, f=N * n / T, T=T)
        op, W = build(signal, pl)
        drift = loop_degradation(op.factors(), W, loops=1)[0]
        img = gray(materialize(op), pct=args.clip)
        if base is None:
            base = img - 0.5
            corr = 1.0
        else:
            a, b = base.ravel(), (img[:args.n0, :args.n0] - 0.5).ravel()
            corr = float(a @ b / np.sqrt((a @ a) * (b @ b)))
        phi = features(img)
        rows.append({"n": n, "delta": d, "rho": pl.rho, "drift": drift,
                     "corr_vs_base": corr,
                     "phi": dict(zip(METRIC_NAMES, map(float, phi)))})
        save_rgb(np.repeat(img[:, :, None], 3, axis=2), OUT / f"n_{n}.png")
        tiles.append((f"n={n} (+{d})  rho={pl.rho:.3f}  corr={corr:+.2f}  "
                      f"moire={rows[-1]['phi']['moire_salience']:.2f}", img))
        print(f"  n={n}: rho={pl.rho:.3f} drift={drift:.1e} "
              f"corr={corr:+.3f} moire={rows[-1]['phi']['moire_salience']:.2f}")

    (OUT / "results.json").write_text(json.dumps(
        {"track": args.track, "f": args.f, "clip": args.clip, "rows": rows},
        indent=2))

    keys = ["beta_slope", "rms_contrast", "entropy", "edge_density",
            "moire_salience"]
    lines = ["| n | +d | rho | drift | corr vs n0 | "
             + " | ".join(keys) + " |",
             "|---" * (5 + len(keys)) + "|"]
    for r in rows:
        lines.append(f"| {r['n']} | +{r['delta']} | {r['rho']:.3f} "
                     f"| {r['drift']:.0e} | {r['corr_vs_base']:+.3f} | "
                     + " | ".join(f"{r['phi'][k]:.2f}" for k in keys) + " |")
    make_sheet(tiles, OUT / "moire_n.png", tile_size=440, cols=len(tiles),
               readme=f"""\
# exp_moire_n: texture sensitivity to the window length n

Track {args.track} at f={args.f:.0f} Hz, clip {args.clip}: n = n0 + d for
d in {deltas}. Interference patterns are generated by n mod p per pitch
period p, so d=1 should reshuffle the moire geometry completely while
rho, drift, and aggregate metrics stay put. corr is the pixel
correlation of the overlapping n0 x n0 signed region against the d=0
baseline: ~1 = same picture, ~0 = fully reshuffled.

{chr(10).join(lines)}

Tiles are downscaled full matrices (downscaling itself aliases the
weave) - judge at 100% via the full-res n_<n>.png files here.
""")
    print(f"wrote {OUT}/moire_n.png and per-n full-res PNGs")


if __name__ == "__main__":
    main()
